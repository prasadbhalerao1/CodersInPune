"""Transactional outbox: the source of truth for domain events.

A row is written in the same transaction as the domain change it describes. Procrastinate
jobs only *carry* (tenant_id, event_id) to a worker; processing state lives here.
"""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import CheckConstraint, DateTime, ForeignKey, Index, Text, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from relay.shared.db.base import Base


class OutboxEvent(Base):
    __tablename__ = "outbox_event"
    __table_args__ = (
        UniqueConstraint("tenant_id", "id"),
        CheckConstraint(r"event_type ~ '^[a-z_]+(\.[a-z_]+)+$'", name="event_type_format"),
        Index(None, "tenant_id", "processed_at"),
        {"schema": "platform"},
    )

    # Generated by the producer so the job can reference it inside the same transaction.
    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    tenant_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("platform.tenant.id"))
    event_type: Mapped[str] = mapped_column(Text)
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    processed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    attempts: Mapped[int] = mapped_column(server_default="0")
    # Exception class name only; messages can contain data and are not stored.
    last_error_type: Mapped[str | None] = mapped_column(Text)
